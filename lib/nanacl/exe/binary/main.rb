# frozen_string_literal: true
require "base64"
require "fileutils"
require "tmpdir"
require "zlib"
require_relative "../expand/expand"

def run(args)
  subparser =
    OptionParser.new do |opts|
      opts.banner = "Usage: nanacl binary [options] FILE [OUTPUT]"
      opts.on("-h", "--help", "Prints this help") do
        puts opts
        exit
      end
      opts.on("-I DIR", "Add a library search path.") do |path|
        $LOAD_PATH.unshift(File.expand_path(path))
      end
    end
  subparser.parse!(args)

  if args.empty?
    puts subparser.help
    return
  end
  file, output = args
  unless File.file?(file)
    warn "File not found: #{file}"
    exit(1)
  end

  original_source = File.read(file)
  content =
    Dir.mktmpdir("nanacl-") do |dir|
      binary = File.join(dir, "main")
      expanded =
        expand(
          original_source,
          File.expand_path(file),
          mode: :blacklist,
          includes: [],
          excludes: [],
          preset: :vanilla,
          main_first: false
        )
      unless expanded[:errored_libraries].empty?
        warn "Library expansion failed."
        exit(1)
      end
      source = File.join(dir, "main.rb")
      File.write(source, expanded[:content])
      unless system(
               "spinel",
               *$LOAD_PATH.flat_map { |path| ["-I", path] },
               "--strict-require",
               "--link",
               "-s",
               source,
               "-o",
               binary,
               out: $stderr
             )
        warn "Spinel compilation failed."
        exit(1)
      end
      encoded =
        Base64.strict_encode64(
          Zlib::Deflate.deflate(File.binread(binary), Zlib::BEST_COMPRESSION)
        )
      <<~RUBY
        # frozen_string_literal: true
        # This file is generated by nanacl using Spinel.
        # Original source code available under `__END__`.
        require "English"
        require "base64"
        require "tmpdir"
        require "zlib"

        online_judge = ENV.key?("ONLINE_JUDGE")
        dir = online_judge ? "/tmp" : Dir.mktmpdir("nanacl-")
        binary = File.join(dir, "nanacl-\#{Process.pid}")
        File.open(binary, "wbx", 0o700) do |file|
          file.write(Zlib::Inflate.inflate(Base64.strict_decode64(#{encoded.dump})))
          file.close
          system(binary, *ARGV, exception: false)
          status = $CHILD_STATUS
          exit(status.signaled? ? 128 + status.termsig : status.exitstatus)
        ensure
          File.unlink(binary)
          Dir.rmdir(dir) unless online_judge
        end
      RUBY
    end
  content << "\n__END__\n" << original_source

  if output
    FileUtils.mkdir_p(File.dirname(output))
    File.write(output, content)
  else
    print content
  end
end
